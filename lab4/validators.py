"""Валидация ввода: проверка типа, диапазона и циклический ввод до корректного значения.

В этом модуле запрещён match-case — только if-elif-else и try/except.
"""
# Импортируем допустимые минимумы и максимумы из файла constants.py
from constants import M_MIN, M_MAX, W1_MIN, W1_MAX, W2_MIN, W2_MAX, T_MIN, T_MAX
# Импортируем функцию log_error, чтобы записывать неудачные попытки ввода в журнал
from logger import log_error


def validate_range(value: float, low: float, high: float) -> tuple[bool, str]:
    """Проверяет попадание значения в диапазон [low, high].

    Args:
        value: проверяемое число.
        low: нижняя граница диапазона.
        high: верхняя граница диапазона.

    Returns:
        Кортеж (True, "") при успехе или (False, сообщение) при ошибке.
    """
    # Проверяем три случая через обязательную цепочку if-elif-else:
    if value < low:
        # 1. Число меньше минимума — возвращаем False (неудача) и текст причины
        return False, f"значение {value} меньше допустимого ({low})"
    elif value > high:
        # 2. Число больше максимума — возвращаем False и текст причины
        return False, f"значение {value} больше допустимого ({high})"
    else:
        # 3. Число попало в нужный интервал — возвращаем True (успех) и пустую строку
        return True, ""


def input_number(prompt: str, low: float, high: float) -> float:
    """Циклически запрашивает число: проверка типа через try/except, границ — через validate_range.

    Args:
        prompt: текст приглашения к вводу.
        low: нижняя граница диапазона.
        high: верхняя граница диапазона.

    Returns:
        Корректное значение типа float.
    """
    is_valid = False  # флаг-переключатель: пока False, цикл не выпустит пользователя
    value = 0.0       # заготовка переменной для будущего числа
    while not is_valid:  # крутимся по кругу, пока пользователь не введёт правильное число
        raw = input(prompt)  # считываем ответ с клавиатуры как обычную строку текста
        try:
            # Пытаемся превратить текст в дробное число (float)
            value = float(raw)
        except ValueError:
            # Если ввели буквы или мусор — срабатывает защита, программа не падает
            msg = f"Ошибка: '{raw}' не является числом"
            print(msg)  # показываем ошибку на экране
            log_error(f"Некорректный ввод: {raw!r} (ожидалось число)")  # пишем в лог
            continue  # сразу прыгаем в начало цикла while, чтобы спросить заново

        # Если превратить в число удалось, проверяем границы через нашу верхнюю функцию
        ok, msg = validate_range(value, low, high)
        if ok:
            # Число в границах — поднимаем флаг True, цикл while после этого завершится
            is_valid = True
        else:
            # Число вышло за границы — выводим причину, пишем в лог и идём на новый круг
            print(f"Ошибка: {msg}")
            log_error(f"Вне диапазона: {value} (допустимо {low}…{high})")
    return value  # возвращаем проверенное число наружу


# Ниже идут удобные функции-обёртки для каждого параметра, чтобы не писать границы вручную в main.py:

def input_mass() -> float:
    """Обёртка: ввод массы материала, кг."""
    return input_number(f"Введите массу материала m (кг, {M_MIN}…{M_MAX}): ", M_MIN, M_MAX)


def input_w1() -> float:
    """Обёртка: ввод начальной влажности, %."""
    return input_number(f"Введите начальную влажность w1 (%, {W1_MIN}…{W1_MAX}): ", W1_MIN, W1_MAX)


def input_w2(w1: float) -> float:
    """Ввод конечной влажности в цикле, пока не выполнится 0 < w2 < w1.

    Args:
        w1: начальная влажность, %.

    Returns:
        Корректная конечная влажность, %.
    """
    # Дополнительный цикл для проверки связи между w2 и w1 (по условию нужно w2 < w1)
    while True:
        # Сначала получаем число в диапазоне 0..30 через общую функцию input_number
        value = input_number(f"Введите конечную влажность w2 (%, {W2_MIN}…{W2_MAX}): ", W2_MIN, W2_MAX)
        if value <= 0:
            # Защита от деления на ноль в формуле логарифма ln(w1 / w2)
            print("Ошибка: конечная влажность должна быть больше 0 (иначе ln(w1/w2) не определён)")
            log_error(f"w2 = {value} недопустимо: требуется w2 > 0")
        elif value >= w1:
            # Конечная влажность после сушки не может быть больше или равна начальной
            print(f"Ошибка: конечная влажность должна быть меньше начальной ({w1})")
            log_error(f"w2 = {value} >= w1 = {w1}")
        else:
            # Все условия выполнены (0 < w2 < w1) — выходим из цикла и возвращаем число
            return value


def input_temperature() -> float:
    """Обёртка: ввод температуры сушильного агента, °C."""
    return input_number(f"Введите температуру сушильного агента (°C, {T_MIN}…{T_MAX}): ", T_MIN, T_MAX)