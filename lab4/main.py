"""Точка входа: связывает модули и реализует главный цикл программы."""
# Подключаем функции для работы с меню из файла menu.py
from menu import show_menu, select_mode, mode_name
# Подключаем функции безопасного ввода с проверками из файла validators.py
from validators import input_mass, input_w1, input_w2, input_temperature
# Подключаем функции расчётов по формулам и классификации из файла operations.py
from operations import water_mass, drying_time, drying_class


def main() -> None:
    """Главный сценарий: цикл расчётов до выбора выхода."""
    print("Вариант 10. Время сушки влажного материала.")  # выводим заголовок программы
    
    # Запускаем бесконечный цикл, чтобы пользователь мог делать расчёты подряд, пока не выберет выход
    while True:
        show_menu()         # печатаем на экране список материалов (1, 2, 3) и пункт выхода (0)
        k = select_mode()   # просим выбрать пункт меню и получаем коэффициент k (или None, если выбрали 0)
        
        if k is None:
            # Если пользователь выбрал 0 (выход), прощаемся и прерываем цикл командой break
            print("Работа завершена.")  #
            break

        # По очереди запрашиваем у пользователя все входные параметры (каждая функция сама проверит тип и границы)
        m = input_mass()            # масса материала в кг
        w1 = input_w1()             # начальная влажность в %
        w2 = input_w2(w1)           # конечная влажность в % (передаём w1, чтобы проверить условие w2 < w1)
        temp = input_temperature()  # температура сушильного агента в °C

        # Передаём проверенные числа в функции расчёта из operations.py
        m_water = water_mass(m, w1, w2)     # считаем массу удаляемой воды
        tau = drying_time(k, w1, w2)        # считаем время сушки в часах
        cls = drying_class(tau)             # определяем класс сушки (быстрая / нормальная / длительная)

        # Красиво выводим результаты на экран с единицами измерения и округлением до 2 знаков после запятой (:.2f)
        print("\n--- Результаты расчёта ---")
        print(f"Материал: {mode_name(k)} (k = {k} 1/ч)")
        print(f"Масса материала: {m:.2f} кг")
        print(f"Влажность: w1 = {w1:.2f} %, w2 = {w2:.2f} %")
        print(f"Температура сушильного агента: {temp:.2f} °C")
        print(f"Масса удаляемой воды: {m_water:.2f} кг")
        print(f"Время сушки: {tau:.2f} ч")
        print(f"Класс: {cls}")


# Стандартная точка входа: запускает функцию main() только тогда, когда мы запускаем сам файл main.py
if __name__ == "__main__":
    main()