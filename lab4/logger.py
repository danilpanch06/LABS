"""Журнал ошибок ввода: хранит записи в памяти и дублирует их в файл."""
import datetime  # подключаем модуль для работы со временем (чтобы ставить дату и время ошибки)

# Импортируем имя файла ("input_errors.log") из constants.py
from constants import LOG_FILE

# Создаём внутренний список в оперативной памяти, куда будем складывать строки ошибок
_entries: list[str] = []


def log_error(message: str) -> None:
    """Добавляет запись в журнал и дописывает её в файл LOG_FILE.

    Args:
        message: текст сообщения об ошибке.
    """
    # Берём текущее время на компьютере и превращаем в красивую строку [ГГГГ-ММ-ДД ЧЧ:ММ:СС]
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    # Склеиваем метку времени и сам текст ошибки в одну строку
    record = f"[{stamp}] {message}"
    # Сохраняем эту строку в наш список _entries в памяти программы
    _entries.append(record)

    # Пытаемся открыть текстовый файл на диске и дописать ошибку в конец
    try:
        # Режим "a" (append) — дописать в конец файла, не стирая старые записи; encoding="utf-8" — чтобы русские буквы не превратились в иероглифы
        with open(LOG_FILE, "a", encoding="utf-8") as f:
            f.write(record + "\n")  # записываем строку и переводим курсор на новую строчку (\n)
    except OSError:
        # Если файл заблокирован или нет прав на запись — программа не упадет с ошибкой, а просто пойдёт дальше (pass)
        pass


def get_entries() -> list[str]:
    """Возвращает копию журнала в памяти."""
    # Возвращаем копию списка _entries (через list(...)), чтобы никто снаружи случайно не испортил оригинал
    return list(_entries)


def clear() -> None:
    """Очищает журнал (используется в тестах)."""
    # Удаляет все записи из списка в памяти (вызывается в tests.py перед каждым новым тестом)
    _entries.clear()