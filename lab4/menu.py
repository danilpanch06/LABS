"""Меню выбора материала и маршрутизация через match-case."""
# Импортируем коэффициенты скорости сушки для каждого материала из constants.py
from constants import K_WOOD, K_CERAMIC, K_GRAIN
# Импортируем log_error, чтобы записывать в журнал, если пользователь введёт неверный пункт меню
from logger import log_error


def show_menu() -> None:
    """Выводит пункты меню на экран."""
    # Просто печатаем доступные варианты выбора для пользователя
    print("\n=== Расчёт времени сушки влажного материала ===")
    print("1 — древесина   (k = 0.008 1/ч)")  #
    print("2 — керамика    (k = 0.004 1/ч)")  #
    print("3 — зерно       (k = 0.012 1/ч)")  #
    print("0 — выход")  #


def select_mode() -> float | None:
    """Циклически запрашивает пункт меню; маршрутизация — только match-case.

    Returns:
        Коэффициент k выбранного материала или None при выходе.
    """
    # Запускаем цикл, который не выпустит пользователя, пока он не выберет 1, 2, 3 или 0
    while True:
        # Считываем ввод и методом .strip() убираем случайные пробелы по краям
        choice = input("Выберите режим (0 — выход): ").strip()
        
        # Обязательная конструкция match-case (работает как переключатель вариантов)
        match choice:
            case "1":
                # Выбрана древесина — возвращаем её коэффициент k = 0.008
                return K_WOOD
            case "2":
                # Выбрана керамика — возвращаем её коэффициент k = 0.004
                return K_CERAMIC
            case "3":
                # Выбрано зерно — возвращаем его коэффициент k = 0.012
                return K_GRAIN
            case "0":
                # Выбран выход — возвращаем специальное пустое значение None (сигнал для main.py завершить работу)
                return None
            case _:
                # Символ _ означает «все остальные случаи» (если ввели 4, букву или пустую строку)
                print("Ошибка: нет такого пункта меню")  #
                log_error(f"Неверный пункт меню: {choice}")  # записываем ошибку в журнал


def mode_name(k: float) -> str:
    """Возвращает название материала по коэффициенту k (match-case).

    Args:
        k: коэффициент скорости сушки.

    Returns:
        Название материала.
    """
    # По значению коэффициента k подбираем красивое название материала для итогового вывода
    match k:
        case 0.008:
            return "древесина"  #